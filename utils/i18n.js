export const state = reactive({
	lang: uni.getStorageSync(LANG_KEY) || 'zh'
})

export function getLang() {
	return state.lang
}

export function setLang(lang) {
	state.lang = lang
	uni.setStorageSync(LANG_KEY, lang)
	syncTabBar()
	syncNavTitle()
}

export function t(key, params) {
	const dict = messages[state.lang] || messages.zh
	let s = dict[key]
	if (s == null) s = key
	if (params) {
		Object.keys(params).forEach((k) => {
			s = s.replace('{' + k + '}', params[k])
		})
	}
	return s
}

// 页面路由 → 导航栏标题 key
const navKeys = {
	'pages/index/index': 'tabFocus',
	'pages/task/task': 'tabTask',
	'pages/stat/stat': 'tabStat',
	'pages/me/me': 'tabMe',
	'pages/login/login': 'login',
	'pages/rank/rank': 'rank',
	'pages/ai/ai': 'aiReport',
	'pages/share/share': 'sharePoster',
	'pages/achievement/achievement': 'achievements'
}

// 底部标签栏顺序固定：专注/任务/统计/我的
const tabBarItems = [
	{ index: 0, key: 'tabFocus' },
	{ index: 1, key: 'tabTask' },
	{ index: 2, key: 'tabStat' },
	{ index: 3, key: 'tabMe' }
]

export function syncNavTitle() {
	const pages = getCurrentPages()
	const route = pages && pages.length ? pages[pages.length - 1].route : ''
	const key = navKeys[route]
	if (key) uni.setNavigationBarTitle({ title: t(key) })
}

export function syncTabBar() {
	tabBarItems.forEach((it) => {
		uni.setTabBarItem({ index: it.index, text: t(it.key) })
	})
}
